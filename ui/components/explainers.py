"""小白概念解释：含税/不含税、权责发生制 vs 收付实现制（v1.19）。"""

from __future__ import annotations

import streamlit as st


def basics() -> None:
    """在算税/台账/申报页调用：折叠式基础概念解释，不占主流程空间。"""
    with st.expander("📘 小白必读：含税/不含税、权责发生制", expanded=False):
        st.markdown(
            """
**1. 含税价与不含税价**

- 含税价 = 你实际收到的钱（价税合计）；不含税价 = 计入收入的钱；税额 = 含税 − 不含税。
- 换算公式：`不含税 = 含税 ÷ (1 + 征收率/税率)`；`税额 = 含税 − 不含税`。
- 例：含税 103,000 元、征收率 3% → 不含税 100,000 元，税额 3,000 元。
- 例：含税 101,000 元、征收率 1% → 不含税 100,000 元，税额 1,000 元。
- 系统会自动换算；但申报表要求填**不含税销售额**，不要把含税金额直接填进去。

**2. 权责发生制 vs 收付实现制**

- 权责发生制：业务发生的月份确认收入/费用，**不管钱有没有收到/付出**。企业会计和申报通常按这个。
- 收付实现制：收到钱/付出钱才确认（个体户简易账有时用）。
- 例：12 月开票、次年 1 月收款 → 收入算在 12 月，不是 1 月；否则跨期错报。
- 例：12 月费用发票次年 1 月才拿到 → 先计提，汇算清缴前取得合规凭证可扣除。

> 小白最容易错：把“收到款”当“确认收入”，或把“付了钱”当“费用发生”。拿不准时先看合同/服务完成时间，再问 AI 助手或专业人士。
            """
        )


