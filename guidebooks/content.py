def list_workflows() -> list[dict[str, Any]]:
    return [{"id": key, **value} for key, value in WORKFLOWS.items()]


def get_workflow(key: str) -> dict[str, Any] | None:
    value = WORKFLOWS.get(str(key))
    return {"id": key, **value} if value else None


def step_count(key: str) -> int:
    workflow = get_workflow(key) or {}
    return len(workflow.get("steps") or [])


